#!/bin/bash
# build.sh: make the title menus and the start screen text (titlemenus.py, startscreen.py), place the sections and refresh cached values until stable (layout.py, fixup.py),
# write the build id, check the graphics limits (gfxlimits.py), assemble doom.asm -> build/doom.sfc
# (ASAR=<asar>), then pad it and set the header and checksum (romcheck.py).  make runs it.
set -e
cd "$(dirname "$0")/.."
ASAR=${ASAR:-asar}
[ -f src/buildid.inc ] || echo '!BUILDID = $00000000' > src/buildid.inc
# the title menus from tools/menus/Title*.png and the data set's slot menu (into data/)
python3 tools/titlemenus.py --data data > build/titlemenus.log
# the start screen's text: the PC start-up log of the data set's WAD
python3 tools/startscreen.py --data data > build/startscreen.log
# the music chunks packed by 32 KB pages for window A
python3 tools/musicpage.py --data data > build/musicpage.log
for i in 1 2 3 4 5 6; do
  before=$(cat src/layout.inc src/engine/*.asm src/include/*.inc | md5sum)
  python3 tools/layout.py > build/layout.log
  python3 tools/fixup.py > build/fixup.log
  after=$(cat src/layout.inc src/engine/*.asm src/include/*.inc | md5sum)
  [ "$before" == "$after" ] && break
done
tail -1 build/layout.log
# build id: save games only load into the ROM build that wrote them
python3 - <<'PY'
import glob, zlib
c = 0
for f in sorted(glob.glob('src/**/*.asm', recursive=True) + glob.glob('src/**/*.inc', recursive=True) + ['data/RLLEV/levels.inc']):
    if f.endswith('buildid.inc'): continue
    c = zlib.crc32(open(f, 'rb').read(), c)
open('src/buildid.inc', 'w').write('!BUILDID = $%08X\t; (generated by tools/build.sh)\n' % c)
PY
python3 tools/gfxlimits.py > build/gfxlimits.log || { cat build/gfxlimits.log; exit 1; }
rm -f build/doom.sfc
$ASAR -I. --fix-checksum=off --symbols=wla --symbols-path=build/doom.sym doom.asm build/doom.sfc 2>&1 | grep -v W65816 || true
python3 tools/romcheck.py build/doom.sfc
