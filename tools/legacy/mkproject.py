#!/usr/bin/env python3
"""Generate the asar project tree from the original DOOM-FX sources.

  mkproject.py <orig-source-dir> <project-dir>

Runs xa2asar.py (data directory: $XLAT_DATA, default the repository's data/),
copies its engine/, include/ and rlmus/ output to src/, then writes
src/layout.inc (section placement), tools/sections.json, src/macros.inc (the
repository's) and doom.asm (master file).

Legacy: it created the first version of this tree, which has been edited by
hand since (doom.asm now uses norom and src/layout_end.inc; tools/layout.py
writes src/layout.inc).  Do not run it on this repository: it replaces
src/engine, src/include, src/rlmus and tools/sections.json."""
import os, sys, json, shutil, subprocess, re
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

def snes_real(load, org):
    off = load - 0x80000000
    # does org map to the same file offset in the sfxrom map?
    if org >= 0x400000 and org < 0x600000 and (org & 0x3FFFFF) == off:
        return org
    if org < 0x400000 and (org & 0x8000) and (((org & 0x7F0000) >> 1) | (org & 0x7FFF)) == off:
        return org
    return 0x400000 + off

def write_layout(info, path):
    lines = [';', ';\tSECTION PLACEMENT  (generated by tools/layout.py - do not edit by hand)', ';',
             ';\treal = ROM position (sfxrom address), pc = CPU address the code is assembled for', ';']
    for name in info['order']:
        load, org = info['placement'][name]
        cname = re.sub(r'[^A-Za-z0-9_]', '_', name)
        if load is None or org is None:
            continue
        if load >= 0x80000000:
            real = snes_real(load, org); ram = 0
        else:
            real = 0x400000; ram = 1
        lines.append('!sec_%s_real = $%06X\t\t; %s' % (cname, real, 'RAM' if ram else 'file $%06X' % (load - 0x80000000)))
        lines.append('!sec_%s_pc = $%06X' % (cname, org))
        lines.append('!sec_%s_ram = %d' % (cname, ram))
    open(path, 'w').write('\n'.join(lines) + '\n')

def main():
    src, proj = sys.argv[1], sys.argv[2]
    data = os.environ.get('XLAT_DATA') or os.path.join(REPO, 'data')
    tmp = os.path.join(proj, '_xlat')
    shutil.rmtree(tmp, ignore_errors=True)
    subprocess.check_call([sys.executable, os.path.join(HERE, 'xa2asar.py'), src, data, tmp])
    os.makedirs(os.path.join(proj, 'src'), exist_ok=True)
    for d in ('engine', 'include', 'rlmus'):
        dst = os.path.join(proj, 'src', d)
        shutil.rmtree(dst, ignore_errors=True)
        if os.path.isdir(os.path.join(tmp, d)):
            shutil.copytree(os.path.join(tmp, d), dst)
    info = json.load(open(os.path.join(tmp, 'xlat_info.json')))
    write_layout(info, os.path.join(proj, 'src', 'layout.inc'))
    # section metadata for tools/layout.py
    meta = {}
    for name in info['order']:
        load, org = info['placement'][name]
        if load is None or org is None: continue
        attrs = info['sections'].get(name, {})
        cname = re.sub(r'[^A-Za-z0-9_]', '_', name)
        ram = load < 0x80000000
        if 'LOAD' in attrs or 'ORG' in attrs or ram:
            kind = 'fixed'
        elif str(attrs.get('RORG', '')).upper() == '$8000':
            kind = 'lorom'
        else:
            kind = 'reloc'
        m = {'kind': kind, 'ram': ram, 'code': name in info.get('code', []),
             'home_file': (load - 0x80000000) if not ram else 0,
             'real': snes_real(load, org) if not ram else 0x400000, 'pc': org}
        if not ram: m['file'] = load - 0x80000000
        if 'ALIGN' in attrs: m['align'] = int(str(attrs['ALIGN']).replace('$', '0x'), 0)
        meta[cname] = m
    os.makedirs(os.path.join(proj, 'tools'), exist_ok=True)
    json.dump(meta, open(os.path.join(proj, 'tools', 'sections.json'), 'w'), indent=1)
    mac = os.path.join(proj, 'src', 'macros.inc')
    if not os.path.exists(mac) or not os.path.samefile(mac, os.path.join(REPO, 'src', 'macros.inc')):
        shutil.copy(os.path.join(REPO, 'src', 'macros.inc'), mac)
    mods = info['modules']
    main = ['; DOOM for the Super Nintendo / Super FX 2 (GSU-2)',
            '; Reality Engine by Randy Linden, Sculptured Software 1995.',
            '; Master assembly file for asar (https://github.com/RPGHacker/asar).',
            ';', ';\tasar -I. doom.asm build/doom.sfc', ';',
            'sfxrom',
            'warnings disable Wfeature_deprecated',
            'math pri on\t\t\t; operator precedence',
            'math round on\t\t\t; integer math (as the original xa assembler)',
            '',
            'incsrc "src/macros.inc"',
            'incsrc "src/layout.inc"',
            '']
    for m in mods:
        main.append('incsrc "src/engine/%s.asm"' % os.path.splitext(m)[0].lower())
    main += ['', '%section_close()', '']
    main += ['', ';', ';\tsection end positions, used by tools/layout.py', ';', 'if defined("PRINT_LAYOUT")']
    for name in info['order']:
        load, org = info['placement'][name]
        if load is None or org is None: continue
        cname = re.sub(r'[^A-Za-z0-9_]', '_', name)
        main.append('\tprint "SECEND %s ",hex(!sec_%s_real)," ",hex(!sec_%s_pc)' % (cname, cname, cname))
    main += ['endif', '']
    open(os.path.join(proj, 'doom.asm'), 'w').write('\n'.join(main))
    shutil.rmtree(tmp, ignore_errors=True)

if __name__ == '__main__':
    main()
