#!/usr/bin/env python3
"""
startscreen.py - the start screen's text (startscreen.asm), as the PC game's start-up log.

  python3 tools/startscreen.py [--data DATA]

The start screen shows while the sound driver loads.  This port fills it with
the PC start-up log (shortened to 32 columns), for the WAD the data set was made
from: the title bar, "adding doom2.wad", the shareware / do-not-distribute notice.
The game is found from the data set's RLLEV/levels.inc: !RLORDERSCREEN =
shareware, !RLMAP07 set = a DOOM II set (TNT / Plutonia by the first map's name),
otherwise The Ultimate DOOM.  The log itself is the PC executable's, not the WAD's.  tools/build.sh runs this before every build.

Writes DATA/RLDATA/COMP/starttext.inc: StartSText (the SystemText list, BG1 map
at $2000; the title on row BAR, startscreen.asm's !STARTBARROW).
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
COLS = 32
SEP = '_' * COLS            # (the text font's '_' is a full-width double line: DOS's =====)
BAR = 1                    # the title bar's row (row 0 can be hidden by the TV; startscreen.asm !STARTBARROW)

GAMES = {
    #  key        title bar                            WAD            version line            notice
    'doom':     ('The Ultimate DOOM Startup v1.9',     'doom.wad',     'registered version.',  'registered'),
    'doom1':    ('DOOM Shareware Startup v1.9',        'doom1.wad',    'shareware version.',   'shareware'),
    'doom2':    ('DOOM 2: Hell on Earth v1.9',         'doom2.wad',    'commercial version.',  'commercial'),
    'plutonia': ('DOOM 2: Plutonia Experiment v1.9',   'plutonia.wad', 'commercial version.',  'commercial'),
    'tnt':      ('DOOM 2: TNT - Evilution v1.9',       'tnt.wad',      'commercial version.',  'commercial'),
}
NOTICES = {
    'shareware': ['Shareware!'],
    'registered': ['This version is NOT SHAREWARE,', 'do not distribute!',
                   'Please report software piracy', 'to the SPA: 1 800 388 PIR8'],
    'commercial': ['Commercial product -', 'do not distribute!',
                   'Please report software piracy', 'to the SPA: 1-800-388-PIR8'],
}


def game(levels_inc):
    s = open(levels_inc).read()
    m = re.search(r'!lvlname0\s*=\s*"([^"]*)"', s)
    first = m.group(1) if m else ''
    if re.search(r'^\s*!RLORDERSCREEN\s*=', s, re.M):
        return 'doom1'
    m = re.search(r'^\s*!RLMAP07\s*=\s*(\$?)([0-9A-Fa-f]+)', s, re.M)
    if m and int(m.group(2), 16 if m.group(1) else 10):
        return {'CONGO': 'plutonia', 'SYSTEM CONTROL': 'tnt'}.get(first, 'doom2')
    return 'doom'


def lines(key):
    title, wad, version, notice = GAMES[key]
    centre = lambda t: (COLS - len(t)) // 2
    out = [(BAR, centre(title), title)]
    log = ['P_Init: Checking cmd line', ' parameters...',
           'V_Init: allocate screens.',
           'M_LoadDefaults: Load system', ' defaults.',
           'Z_Init: Init zone memory', ' allocation daemon.',
           'DPMI memory: 0xdb0000,', ' 0x800000 allocated for zone',
           'W_Init: Init WADfiles.',
           '        adding ' + wad,
           '        ' + version,
           SEP]
    log += [' ' * centre(t) + t for t in NOTICES[notice]]
    log += [SEP,
            'M_Init: Init miscellaneous info.',
            'R_Init: Init DOOM refresh',
            ' daemon  [.....            ]']
    row = BAR + 2
    for t in log:
        out.append((row, len(t) - len(t.lstrip(' ')), t.strip(' ')))
        row += 1
    if row > 27:
        sys.exit('start screen: %d rows' % row)
    for r, c, t in out:
        if c + len(t) > COLS or '"' in t:
            sys.exit('start screen: line "%s" does not fit' % t)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--data', default=os.path.join(HERE, '..', 'data'))
    a = ap.parse_args()
    key = game(os.path.join(a.data, 'RLLEV', 'levels.inc'))
    out = lines(key)
    inc = ['; generated by tools/startscreen.py -- do not edit (%s)' % GAMES[key][1],
           'StartSText:']
    for i, (r, c, t) in enumerate(out):
        if t:
            inc += ['\tdw ($2000+(%d*32)+%d)' % (r, c), '\tdl .t%d' % i, '\tdb %d' % len(t)]
    inc.append('\tdw -1')
    for i, (r, c, t) in enumerate(out):
        if t:
            inc.append('.t%d:\tdb "%s"' % (i, t))
    open(os.path.join(a.data, 'RLDATA', 'COMP', 'starttext.inc'), 'w').write('\n'.join(inc) + '\n')
    print('start screen: %s (%s), %d lines' % (GAMES[key][0], GAMES[key][1], len(out)))


if __name__ == '__main__':
    main()
